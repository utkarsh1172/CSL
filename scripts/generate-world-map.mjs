// Projects Natural Earth country outlines (world-atlas, public domain) into static SVG paths
// for the contact page partner map, so no map library ships to the browser.
// Run: node scripts/generate-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

import { geoEqualEarth, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const countries = feature(topology, topology.objects.countries);

const width = 900;
const height = 450;
const projection = geoEqualEarth().fitSize([width, height], countries);
const path = geoPath(projection).digits(1);

const shapes = countries.features
  .map((country) => ({ id: String(country.id ?? country.properties.name), d: path(country) }))
  .filter((shape) => shape.d);

const [translateX, translateY] = projection.translate();
const output = `// Generated by scripts/generate-world-map.mjs from world-atlas countries-110m. Do not edit.
export const worldMap = {
  width: ${width},
  height: ${height},
  /** Equal Earth projection parameters, so markers can be placed with projectPoint(). */
  scale: ${projection.scale().toFixed(4)},
  translate: [${translateX.toFixed(4)}, ${translateY.toFixed(4)}],
  countries: ${JSON.stringify(shapes)},
} as const;
`;

writeFileSync(new URL("../src/content/pages/contact/world-map.generated.ts", import.meta.url), output);
console.log(`Wrote ${shapes.length} countries (${(output.length / 1024).toFixed(1)} KB).`);

// Sanity check for projectPoint(): Toronto as projected by d3.

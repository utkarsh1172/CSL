// Builds the country dial-code list used by CountryCodeSelect and copies each country's flag
// into public/, so the picker needs no phone-number library or flag font in the browser.
// Run: node scripts/generate-country-codes.mjs
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

import { getCountries, getCountryCallingCode, getExampleNumber } from "libphonenumber-js";
import examples from "libphonenumber-js/mobile/examples";

const require = createRequire(import.meta.url);
// The package does not export its SVG paths, so locate the folder from its package.json.
const flagDir = require.resolve("country-flag-icons/package.json").replace(/package\.json$/, "3x2/");
const outputFlagDir = new URL("../public/images/flags/", import.meta.url);
mkdirSync(outputFlagDir, { recursive: true });

const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

const countries = getCountries()
  .map((code) => {
    const source = `${flagDir}${code}.svg`;
    if (!existsSync(source)) throw new Error(`No flag for ${code}`);
    copyFileSync(source, new URL(`${code.toLowerCase()}.svg`, outputFlagDir));

    return {
      code,
      name: regionNames.of(code) ?? code,
      dialCode: `+${getCountryCallingCode(code)}`,
      // International format minus the dial code, so the placeholder omits national trunk
      // prefixes (UK "7400 123456", not "07400 123456") that don't apply after +44.
      example: getExampleNumber(code, examples)
        ?.formatInternational()
        .replace(/^\+\d+\s*/, ""),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const output = `// Generated by scripts/generate-country-codes.mjs from libphonenumber-js. Do not edit.
export type CountryDialCode = {
  /** ISO 3166-1 alpha-2 code; the flag lives at /images/flags/<code lowercased>.svg. */
  code: string;
  name: string;
  dialCode: string;
  /** An example mobile number without the dial code, used as the phone field's placeholder. */
  example?: string;
};

export const countryDialCodes: readonly CountryDialCode[] = ${JSON.stringify(countries, null, 2)};
`;

writeFileSync(new URL("../src/content/shared/countries.generated.ts", import.meta.url), output);
console.log(`Wrote ${countries.length} countries (${(output.length / 1024).toFixed(1)} KB) and their flags.`);
console.log(countries.filter((c) => ["CA", "IN", "GB", "AE"].includes(c.code)));

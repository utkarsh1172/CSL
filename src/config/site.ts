/**
 * Site identity and canonical origin, shared by page metadata, the sitemap, robots.txt, the web
 * manifest and structured data. Server-only: it reads deployment variables that the browser
 * bundle never sees, so import it from server components and metadata files only.
 */

// The canonical origin, without a trailing slash. NEXT_PUBLIC_SITE_URL wins: set it to the live
// domain (e.g. https://www.example.com). On Vercel the project's production domain is used
// otherwise, so preview deployments still point search engines at production.
function resolveSiteUrl() {
  const configured = process.env.NEXT_PUBLIC_SITE_URL;
  if (configured) return configured.replace(/\/+$/, "");

  const vercelProduction = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (vercelProduction) return `https://${vercelProduction}`;

  return "http://localhost:3000";
}

export const siteUrl = resolveSiteUrl();

/**
 * Only production is indexed. Vercel preview and development deployments answer robots.txt with
 * "Disallow: /" and tag every page noindex, so they never compete with the live site in search.
 */
export const isIndexable = process.env.VERCEL_ENV
  ? process.env.VERCEL_ENV === "production"
  : process.env.NODE_ENV === "production";

